/*
 * Industry colour themes: each brings its own set of colour groups (name,
 * colour tone, keywords) for a kind of flow — supply chains, manufacturing,
 * HR and sales. "Money flow" is the built-in set in finance.ts.
 *
 * A box goes in the first group whose keywords match its name; otherwise its
 * position decides: starting boxes → the "start" group, boxes in between →
 * the "middle" group, end boxes → the "end" group.
 */

export type IndustryId = "finance" | "supply" | "manufacturing" | "hr" | "sales";

/**
 * A colour that follows the light/dark theme. The first five are the Money
 * flow colours (green, gray, crimson, teal, ochre); "blue" is palette blue.
 */
export type Tone = "income" | "account" | "spending" | "savings" | "remainder" | "blue";

export interface PresetGroup {
  name: string;
  tone: Tone;
  keywords: string[];
  /** Unmatched boxes in this position go in this group. */
  position?: "start" | "middle" | "end";
}

export interface IndustryPreset {
  id: IndustryId;
  name: string;
  /** What a box with flows in and out is called (summary table heading). */
  stageWord: string;
  groups: PresetGroup[];
}

